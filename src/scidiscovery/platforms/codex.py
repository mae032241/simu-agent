def _operation_toml(
    compiled: Any,
    *,
    python: Path,
    python_path: Path | None,
    state_root: Path,
    local_workspace_root: Path | None = None,
    worker_backend: str = "local",
    runtime_plugin_configs: Mapping[str, Path] | None = None,
    debug_disable_task_network: bool = False,
) -> str:
    """Compile one Agent Operation into the Codex child-Agent profile."""

    validate_worker_backend(worker_backend)
    executor = compiled.spec.executor
    if not LocalTrustedBackend.supports_operation(compiled):
        raise ValueError(
            "compiled Operation requires native tools unavailable on this backend"
        )
    if local_workspace_root is None:
        raise ValueError("local workspace root is required")
    if executor.prompt is None:
        raise ValueError("compiled Agent operation has no prompt")
    prompt = (
        _local_native_tool_instruction(compiled, debug_disable_task_network=debug_disable_task_network)
        + ("\nDeployment debug policy disables task network, native web search and declared host network tools. "
           "Use sealed/local inputs; requests requiring network are unavailable. Model API transport is unchanged.\n"
           if debug_disable_task_network else "")
        + "\nFor MCP results, consume structuredContent when present; otherwise read text content once. "
        "Never emit both representations of the same result, including from functions.exec. "
        "Preserve isError, distinct diagnostics and needed non-text content such as images.\n"
        + OPERATION_COMPLETION_INSTRUCTIONS
    )
    agent_type = operation_agent_type(compiled)
    shell_enabled = executor.native_tools.shell != "none"
    lines = [
        "# Generated by SciDiscovery. Re-run `scid init codex` to update.",
        f"name = {_quote(agent_type)}",
        f"description = {_quote(operation_agent_description(compiled))}",
        f"web_search = {_quote(task_network_policy(debug_disable_task_network, web_search=executor.native_tools.web_search)['web_search'])}",
        f"developer_instructions = {_quote(prompt)}",
        "",
        "[features]",
        f"shell_tool = {str(shell_enabled).lower()}",
        f"unified_exec = {str(shell_enabled).lower()}",
        "",
        "[tools]",
        f"view_image = {str(executor.native_tools.view_image).lower()}",
        "",
    ]
    content = "\n".join(lines).rstrip() + "\n"
    tomllib.loads(content)
    return content


def _proxy_server_toml(
    *, python: Path, socket_path: Path, python_path: Path | None
) -> str:
    args = (
        "-m",
        "scidiscovery.artifact_agent.interfaces.mcp_proxy",
        "--socket",
        str(socket_path),
    )
    return "\n".join(
        (
            "[mcp_servers.scidiscovery]",
            f"command = {_quote(str(python))}",
            "args = [" + ", ".join(_quote(value) for value in args) + "]",
            "enabled = true",
            "required = true",
            "enabled_tools = ["
            + ", ".join(_quote(tool) for tool in SCHEDULER_TOOLS)
            + "]",
            'default_tools_approval_mode = "approve"',
            _toml_env(
                {
                    "PYTHONNOUSERSITE": "1",
                    "SCIDISCOVERY_PRINCIPAL": "service",
                    **({"PYTHONPATH": str(python_path)} if python_path else {}),
                }
            ),
        )
    )


def _runtime_plugin_config_paths(
    values: Mapping[str, Path | str] | None,
) -> dict[str, Path]:
    result: dict[str, Path] = {}
    for plugin_id, value in (values or {}).items():
        if not plugin_id or plugin_id in result:
            raise ValueError("runtime plugin config identity is invalid")
        result[plugin_id] = _absolute_path(value)
    return result


def _validate_runtime_plugin_config_ids(
    catalog: CompiledCatalog, values: Mapping[str, Path]
) -> None:
    unknown = set(values) - set(catalog.runtime_plugin_ids())
    if unknown:
        raise PlatformConflictError(
            "runtime plugin config is not present in the compiled catalog: "
            + ", ".join(sorted(unknown))
        )


def _toml_env(values: dict[str, str]) -> str:
    entries = ", ".join(
        f"{key} = {_quote(value)}" for key, value in sorted(values.items())
    )
    return f"env = {{ {entries} }}"


def _reject_unmanaged_server(current: str) -> None:
    if not current.strip() or CONFIG_BEGIN in current:
        return
    try:
        parsed = tomllib.loads(current)
    except tomllib.TOMLDecodeError as error:
        raise PlatformConflictError(
            f"existing Codex config is invalid: {error}"
        ) from error
    servers = parsed.get("mcp_servers", {})
    if isinstance(servers, dict) and "scidiscovery" in servers:
        raise PlatformConflictError(
            "existing Codex config owns mcp_servers.scidiscovery"
        )


def _runtime_config_toml(
    current: str,
    *,
    agent_registrations: dict[str, tuple[str, Path]],
    debug_disable_task_network: bool = False,
) -> str:
    unmanaged = _without_managed_block(current)
    try:
        parsed = tomllib.loads(unmanaged)
    except tomllib.TOMLDecodeError as error:
        raise PlatformConflictError(
            f"existing Codex config is invalid: {error}"
        ) from error

    blocks: list[str] = []
    if debug_disable_task_network:
        if (parsed.get("sandbox_mode", "workspace-write") not in {"workspace-write", "read-only"}
                or parsed.get("sandbox_workspace_write", {}).get("network_access") is True
                or parsed.get("web_search", "disabled") != "disabled"):
            raise PlatformConflictError("deployment offline debug policy conflicts with existing Codex network permissions")
        if "web_search" not in parsed:
            # TOML has no way to return to the root after a table. Do not append
            # a scalar to an unrelated existing table and mistake it for a deny.
            if any(isinstance(value, dict) for value in parsed.values()):
                raise PlatformConflictError('declare root web_search="disabled" before existing tables, then initialize offline debug roles')
            blocks.append('web_search = "disabled"')
        if "sandbox_workspace_write" not in parsed:
            blocks.append('[sandbox_workspace_write]\nnetwork_access = false')
        elif parsed['sandbox_workspace_write'].get('network_access') is not False:
            raise PlatformConflictError('declare sandbox_workspace_write.network_access=false before initializing offline debug roles')
    features = parsed.get("features")
    if features is None:
        blocks.append("[features]\nmulti_agent = true")
        features = {}
    elif not isinstance(features, dict) or features.get("multi_agent") is False:
        raise PlatformConflictError(
            "existing Codex [features] explicitly disables multi_agent"
        )
    multi_agent_v2 = features.get("multi_agent_v2")
    if multi_agent_v2 is None:
        blocks.append(
            "[features.multi_agent_v2]\n"
            "enabled = false\n"
            "hide_spawn_agent_metadata = false"
        )
    elif (
        not isinstance(multi_agent_v2, dict)
        or multi_agent_v2.get("enabled") is not False
        or multi_agent_v2.get("hide_spawn_agent_metadata") is True
    ):
        raise PlatformConflictError(
            "Codex multi_agent_v2 does not expose the agent_type routing "
            "required by compiled operation Agents"
        )

    agents = parsed.get("agents")
    if agents is None:
        blocks.append(
            "[agents]\n"
            "enabled = true\n"
            "max_concurrent_threads_per_session = 3"
        )
    elif not isinstance(agents, dict) or agents.get("enabled") is False:
        raise PlatformConflictError(
            "existing Codex [agents] explicitly disables agents"
        )
    for agent_type, (description, config_file) in sorted(
        agent_registrations.items()
    ):
        if isinstance(agents, dict) and agent_type in agents:
            raise PlatformConflictError(
                f"existing Codex config owns agents.{agent_type}"
            )
        blocks.append(
            f"[agents.{_quote(agent_type)}]\n"
            f"description = {_quote(description)}\n"
            f"config_file = {_quote(str(config_file))}"
        )
    return "\n\n".join(blocks)


def _without_managed_block(current: str) -> str:
    return _without_block(current, CONFIG_BEGIN, CONFIG_END)


def _without_block(current: str, begin: str, end: str) -> str:
    if current.count(begin) != current.count(end) or current.count(begin) > 1:
        raise PlatformConflictError("managed block markers are malformed")
    if begin not in current:
        return current
    prefix, remainder = current.split(begin, 1)
    if end not in remainder:
        raise PlatformConflictError("managed block markers are malformed")
    _, suffix = remainder.split(end, 1)
    return prefix + suffix


def _root_instruction_config(current: str, guide_root: Path) -> str:
    unmanaged = _without_block(current, ROOT_BEGIN, ROOT_END)
    try:
        parsed = tomllib.loads(_without_managed_block(unmanaged))
    except tomllib.TOMLDecodeError as error:
        raise PlatformConflictError("existing Codex config is invalid") from error
    if _has_user_developer_instructions(parsed):
        raise PlatformConflictError("project developer_instructions is user-owned; its Root/Worker scope cannot be inferred; preserve it and resolve the configuration conflict before installing")
    prompt = load_scheduler_prompt().replace("{{SCHEDULER_GUIDE_ROOT}}", str(guide_root))
    block = f"{ROOT_BEGIN}\ndeveloper_instructions = {_quote(prompt)}\n{ROOT_END}\n"
    if ROOT_BEGIN in current:
        # Replacing at the same position preserves all user bytes outside it.
        result = managed_block(current, begin=ROOT_BEGIN, end=ROOT_END,
                               body=f"developer_instructions = {_quote(prompt)}")
    else:
        # Root scalar must precede every user or managed TOML table.
        result = block + current
    parsed = tomllib.loads(result)
    if parsed.get("developer_instructions") != prompt:
        raise PlatformConflictError("managed Root developer_instructions must be a top-level TOML value")
    return result


def _reject_user_developer_instructions(root: Path, config_path: Path) -> None:
    personal = Path(os.environ.get("CODEX_HOME", str(Path.home() / ".codex"))) / "config.toml"
    paths = [personal]
    for directory in (root, *root.parents):
        paths.append(directory / ".codex/config.toml")
        if (directory / ".git").exists():
            break
    for path in dict.fromkeys(paths):
        if path.absolute() == config_path.absolute() or not path.is_file():
            continue
        text = _read(path)
        try:
            parsed = tomllib.loads(_without_block(text, ROOT_BEGIN, ROOT_END))
        except tomllib.TOMLDecodeError as error:
            raise PlatformConflictError(f"upstream Codex config is invalid at {path}") from error
        if _has_user_developer_instructions(parsed):
            raise PlatformConflictError(f"upstream Codex developer_instructions at {path} would be shadowed by Root/Worker configuration; its scope cannot be inferred; no user instructions were changed")


def _has_user_developer_instructions(config: dict) -> bool:
    profiles = config.get("profiles", {})
    return "developer_instructions" in config or (isinstance(profiles, dict) and
        any("developer_instructions" in profile for profile in profiles.values() if isinstance(profile, dict)))


def _common_instruction_block(current: str, *, body: str) -> str:
    legacy = PROMPT_BEGIN in current or PROMPT_END in current
    common = COMMON_BEGIN in current or COMMON_END in current
    if legacy and common:
        raise PlatformConflictError("both legacy scheduler and common instruction blocks exist; resolve the managed-block conflict")
    if legacy:
        _without_block(current, PROMPT_BEGIN, PROMPT_END)
        current = current.replace(PROMPT_BEGIN, COMMON_BEGIN).replace(PROMPT_END, COMMON_END)
    return managed_block(current, begin=COMMON_BEGIN, end=COMMON_END, body=body)


def _validate_instruction_profile(root: Path, config: dict) -> None:
    expected = load_scheduler_prompt().replace("{{SCHEDULER_GUIDE_ROOT}}", str(root / ".codex/scidiscovery-guides"))
    if config.get("developer_instructions") != expected:
        raise PlatformConflictError("installed Root developer instructions are missing or stale; regenerate the Codex project profile")
    text = _read(root / "AGENTS.md")
    if PROMPT_BEGIN in text or PROMPT_END in text:
        raise PlatformConflictError("legacy scheduler block remains in shared AGENTS; regenerate the Codex project profile")
    if COMMON_BEGIN not in text or COMMON_END not in text:
        raise PlatformConflictError("installed common instructions are missing")
    _without_block(text, COMMON_BEGIN, COMMON_END)
    body = text.split(COMMON_BEGIN, 1)[1].split(COMMON_END, 1)[0]
    if load_common_prompt().strip() not in body:
        raise PlatformConflictError("installed common instructions are stale")


def _quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _read(path: Path) -> str:
    if not path.exists():
        return ""
    with path.open(encoding="utf-8", newline="") as stream:
        return stream.read()


def _absolute_python_executable(value: Path | str) -> Path:
    expanded = Path(value).expanduser()
    return Path(os.path.abspath(os.fspath(expanded)))


def _absolute_path(value: Path | str) -> Path:
    return Path(os.path.abspath(os.fspath(Path(value).expanduser())))
